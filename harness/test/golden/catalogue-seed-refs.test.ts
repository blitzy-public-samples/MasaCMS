import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { loadCatalogue, scenarioById, type Catalogue, type SeedRef } from '../../src/golden/catalogue.js';
import { GoldenConfigError, MissingSecretError } from '../../src/golden/errors.js';
import {
  SEED_CREDENTIALS_FILE,
  checkSeedRefs,
  createScenarioContext,
  loadSecretStore,
  loadSeedStore,
  type ScenarioInput,
  type SecretStore,
  type SeedRefFinding,
  type SeedStore,
} from '../../src/golden/session.js';
import { stateDir as resolveStateDir, type EnvLike } from '../../src/lib/paths.js';

const SCENARIO = 'GS-CO-09';
const SITE_ADMIN = 'FIXTURE-site-admin';
const ADMIN_WHERE = { siteID: 'tenant-a', groupname: 'Admin' };

const GROUPS = [
  { groupID: 'FIXTURE-GROUP-0001', siteID: 'tenant-a', groupname: 'timesheets.employee' },
  { groupID: 'FIXTURE-GROUP-0002', siteID: 'tenant-b', groupname: 'timesheets.employee' },
];
const USERS = [
  { userID: 'FIXTURE-USER-0001', siteID: 'tenant-a', username: SITE_ADMIN },
  { userID: 'FIXTURE-USER-0002', siteID: 'tenant-b', username: 'FIXTURE-member' },
];
const DATASET = { businessDate: '2026-03-02', masa: { groups: GROUPS, users: USERS } };
const CREDENTIALS = {
  users: { 'tenant-a': { [SITE_ADMIN]: 'FIXTURE-PW' } },
  roles: { 'tenant-a': { 'site-admin': SITE_ADMIN } },
};

// Generated by legacy-fixtures/seed into the run's state directory; the harness never imports that package.
const DATASET_FILE = path.join(resolveStateDir(), 'seed', 'dataset.json');
const HAS_DATASET = fs.existsSync(DATASET_FILE);
const CONTAINS_TEXT = /:contains\("([^"]+)"\)/;
// A `groupname` field anywhere in a step's form, body, multipart fields or candidates.
const GROUPNAME_FIELD = /"groupname":"((?:[^"\\]|\\.)*)"/gi;
const ADMIN_EXTRACTIONS = [
  ['GS-CO-09', 'new-chain'],
  ['GS-BR-01', 'user-form'],
] as const;

interface Files {
  dataset: string;
  credentials: string;
}

let dir: string;
let files: Files;
let env: EnvLike;

beforeEach(() => {
  dir = fs.mkdtempSync(path.join(os.tmpdir(), 'opt2-golden-seed-refs-'));
  files = {
    dataset: path.join(dir, 'seed', 'dataset.json'),
    credentials: path.join(dir, 'secrets', SEED_CREDENTIALS_FILE),
  };
  fs.mkdirSync(path.dirname(files.dataset), { recursive: true });
  fs.writeFileSync(files.dataset, `${JSON.stringify(DATASET)}\n`);
  fs.mkdirSync(path.dirname(files.credentials), { recursive: true, mode: 0o700 });
  fs.writeFileSync(files.credentials, `${JSON.stringify(CREDENTIALS, null, 2)}\n`, { mode: 0o600 });
  env = { PORT: '20080', OPT2_STATE_DIR: dir };
});

afterEach(() => {
  fs.rmSync(dir, { recursive: true, force: true });
});

function stores(): { seed: SeedStore; secrets: SecretStore } {
  return { seed: loadSeedStore(env), secrets: loadSecretStore(env) };
}

function ref(as: string, dataPath: string, where?: SeedRef['where']): SeedRef {
  return { as, source: 'dataset', path: dataPath, ...(where === undefined ? {} : { where }) };
}

/** Error `fn` throws, or undefined when it returns. */
function thrown(fn: () => unknown): unknown {
  try {
    fn();
  } catch (err) {
    return err;
  }
  return undefined;
}

describe('checkSeedRefs', () => {
  it.each<[string, SeedRef[], (f: Files) => Omit<SeedRefFinding, 'scenarioId'>[]]>([
    ['a ref the dataset holds', [ref('group', 'masa.groups', { siteID: 'tenant-a' })], () => []],
    [
      'a ref no row matches',
      [ref('adminGroup', 'masa.groups', ADMIN_WHERE)],
      () => [
        {
          alias: 'adminGroup',
          message:
            `${SCENARIO}: seedRef adminGroup: no row at index 0 among the 0 rows of masa.groups matching ` +
            JSON.stringify(ADMIN_WHERE),
        },
      ],
    ],
    [
      'a path the dataset lacks',
      [ref('people', 'masa.people')],
      (f) => [{ alias: 'people', message: `${SCENARIO}: seedRef people: masa.people is not in ${f.dataset}` }],
    ],
    [
      'a where reading an earlier row',
      [ref('group', 'masa.groups', { siteID: 'tenant-b' }), ref('member', 'masa.users', { siteID: '${seed.group.siteID}' })],
      () => [],
    ],
    ['a where naming a seeded role', [ref('approver', 'masa.users', { username: '${user:tenant-a:site-admin}' })], () => []],
    [
      'a where reading an unresolvable earlier ref',
      [ref('adminGroup', 'masa.groups', ADMIN_WHERE), ref('approver', 'masa.users', { userID: '${seed.adminGroup.userID}' })],
      () => [
        {
          alias: 'adminGroup',
          message:
            `${SCENARIO}: seedRef adminGroup: no row at index 0 among the 0 rows of masa.groups matching ` +
            JSON.stringify(ADMIN_WHERE),
        },
        { alias: 'approver', message: `${SCENARIO}: unresolved placeholder \${seed.adminGroup.userID}` },
      ],
    ],
    [
      'a where naming a role without a username',
      [ref('auditor', 'masa.users', { username: '${user:tenant-a:auditor}' })],
      (f) => [{ alias: 'auditor', message: `${SCENARIO}: \${user:tenant-a:auditor} has no username in ${f.credentials}` }],
    ],
    [
      'a where naming a secret without a value',
      [ref('nobody', 'masa.users', { username: '${secret:seed:nobody}' })],
      (f) => [{ alias: 'nobody', message: `Secret \${secret:seed:nobody} has no unique value in ${f.credentials}` }],
    ],
  ])('checks %s as createScenarioContext resolves it', (_label, seedRefs, expected) => {
    const scenario: ScenarioInput = { id: SCENARIO, seedRefs };
    const findings = checkSeedRefs([scenario], { ...stores(), env });
    expect(findings).toEqual(expected(files).map((finding) => ({ scenarioId: SCENARIO, ...finding })));

    const err = thrown(() => createScenarioContext(scenario, { origin: 'legacy', env, ...stores() }));
    if (findings[0] === undefined) {
      expect(err).toBeUndefined();
    } else {
      expect([GoldenConfigError, MissingSecretError].some((type) => err instanceof type)).toBe(true);
      expect((err as Error).message).toBe(findings[0].message);
    }
  });

  it('checks each scenario apart, so one never reads the rows of another', () => {
    const findings = checkSeedRefs(
      [
        { id: 'GS-AA-01', seedRefs: [ref('group', 'masa.groups')] },
        { id: 'GS-BB-02', seedRefs: [ref('member', 'masa.users', { siteID: '${seed.group.siteID}' })] },
        { id: 'GS-CC-03' },
      ],
      { ...stores(), env },
    );
    expect(findings).toEqual([
      { scenarioId: 'GS-BB-02', alias: 'member', message: 'GS-BB-02: unresolved placeholder ${seed.group.siteID}' },
    ]);
  });

  it('rethrows an error that is not a configuration error', () => {
    const seed: SeedStore = {
      select: () => {
        throw new TypeError('FIXTURE-broken-store');
      },
      businessDate: () => '2026-03-02',
    };
    const scenario: ScenarioInput = { id: SCENARIO, seedRefs: [ref('group', 'masa.groups')] };
    expect(() => checkSeedRefs([scenario], { seed, secrets: loadSecretStore(env), env })).toThrow(TypeError);
  });
});

describe('the committed catalogue', () => {
  let catalogue: Catalogue;

  beforeAll(async () => {
    catalogue = await loadCatalogue();
  });

  function adminTexts(): string[] {
    return ADMIN_EXTRACTIONS.map(([id, stepName]) => {
      const extraction = scenarioById(catalogue, id).steps.find((step) => step.name === stepName)?.extract?.adminGroupID;
      return extraction?.from === 'dom' ? (CONTAINS_TEXT.exec(extraction.selector)?.[1] ?? '') : '';
    });
  }

  it.runIf(HAS_DATASET)(
    HAS_DATASET
      ? `resolves every seedRef against the generated dataset ${DATASET_FILE}`
      : `resolves every seedRef against a generated dataset: skipped, ${DATASET_FILE} is absent`,
    () => {
      expect(checkSeedRefs(catalogue.scenarios, { seed: loadSeedStore(), secrets: loadSecretStore() })).toEqual([]);
    },
  );

  it('selects the Admin group by text that no group a scenario creates contains', () => {
    const texts = adminTexts();
    expect(texts).toEqual(['Admin', 'Admin']);
    const [text] = texts;
    const created = catalogue.scenarios.flatMap((s) =>
      [...JSON.stringify(s.steps).matchAll(GROUPNAME_FIELD)].map((match) => JSON.parse(`"${match[1]}"`) as string),
    );
    expect(created.length).toBeGreaterThan(0);
    expect(created.filter((name) => name.includes(text as string))).toEqual([]);
  });

  it.runIf(HAS_DATASET)(
    HAS_DATASET
      ? `selects the Admin group by text that no group of ${DATASET_FILE} contains`
      : `selects the Admin group by text no generated group contains: skipped, ${DATASET_FILE} is absent`,
    () => {
      const [text] = adminTexts();
      const dataset = JSON.parse(fs.readFileSync(DATASET_FILE, 'utf8')) as { masa: { groups: { groupname: string }[] } };
      const names = dataset.masa.groups.map((group) => group.groupname);
      expect(names.length).toBeGreaterThan(0);
      expect(names.filter((name) => name.includes(text as string))).toEqual([]);
    },
  );
});
