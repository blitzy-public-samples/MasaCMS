const USAGE = 'inventory:assumptions [--live]';
const HELP = `${USAGE} [--help]

Verifies the AAP 0.2.3 assumptions against ${INVENTORY_PATH} and writes ${REPORT_FILE} to the reports directory
(OPT2_REPORTS_DIR, default opt2/reports). A refuted assumption is a reported outcome and still exits 0.

Options:
  --live  add live evidence: read-only SQL Server queries (MURA_DB* variables), ${INFO_PATH}?info=1 on
          LEGACY_ORIGIN (else http://127.0.0.1:$PORT) and \${OPT2_PRISTINE_DIR}/${NATIVE_TASKS_FILE}
  --help  print this help and exit 0
`;

/** Injectable dependencies of {@link main}. */
export interface AssumptionsDeps {
  /** Inventory file; a relative path resolves against the repository root. Default {@link INVENTORY_PATH}. */
  inventoryPath?: string;
  openDb?: (env: EnvLike) => Promise<ReadOnlyMssql>;
  fetch?: FetchLike;
  clock?: () => Date;
}

/** The validated inventory; a missing file names the command that generates it. */
export async function loadAssumptionsInventory(file: string = INVENTORY_PATH): Promise<AssumptionsInventory> {
  try {
    return await readJson(file, inventorySchema);
  } catch (err) {
    if (isMissingFile(err)) throw new Error(`${file} does not exist: run npm run inventory first`, { cause: err });
    throw err;
  }
}

function legacyOrigin(env: EnvLike): string {
  if (env.LEGACY_ORIGIN) return env.LEGACY_ORIGIN;
  if (env.PORT) return `http://127.0.0.1:${env.PORT}`;
  throw new UsageError('--live needs LEGACY_ORIGIN or PORT', USAGE);
}

function displayPath(p: string): string {
  return isInsideRepo(p) ? path.relative(REPO_ROOT, p).split(path.sep).join('/') : p;
}

/** CLI entry: evaluates the assumptions, writes the report and exits 0 whatever the verdicts. */
export async function main(
  argv: string[],
  env: EnvLike = process.env,
  deps: AssumptionsDeps = {},
): Promise<CliOutcome> {
  const { values } = parseFlags(argv, { options: { live: { type: 'boolean' } }, usage: USAGE, help: HELP });
  const inventory = await loadAssumptionsInventory(deps.inventoryPath);
  let live: LiveEvidence | undefined;
  if (values.live === true) {
    const origin = legacyOrigin(env);
    const db = await (deps.openDb ?? createReadOnlyMssql)(env);
    try {
      live = await gatherLiveEvidence({ db, origin, env, fetch: deps.fetch, clock: deps.clock });
    } finally {
      await db.close();
    }
  }
  const rows = evaluateAssumptions(inventory, live);
  const file = await writeMarkdown(
    path.join(reportsDir(env), REPORT_FILE),
    REPORT_TITLE,
    renderAssumptionsMarkdown(rows, live?.checkedAt ?? null),
  );
  return { code: 0, summary: { ...summarise(rows), live: live !== undefined, report: displayPath(file) } };
}

