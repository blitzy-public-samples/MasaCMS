/** Base tables of the legacy database. */
export const CATALOG_TABLES_SQL =
  'SELECT TABLE_SCHEMA AS schemaName, TABLE_NAME AS tableName FROM INFORMATION_SCHEMA.TABLES ' +
  "WHERE TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_SCHEMA, TABLE_NAME";

/** Number of `dbo` base tables with a `siteID` column. */
export const SITE_ID_TABLES_SQL =
  'SELECT COUNT(DISTINCT c.TABLE_NAME) AS tableCount FROM INFORMATION_SCHEMA.COLUMNS c ' +
  'JOIN INFORMATION_SCHEMA.TABLES t ON t.TABLE_SCHEMA = c.TABLE_SCHEMA AND t.TABLE_NAME = c.TABLE_NAME ' +
  "WHERE t.TABLE_TYPE = 'BASE TABLE' AND c.TABLE_SCHEMA = 'dbo' AND LOWER(c.COLUMN_NAME) = 'siteid'";

/** Fixture program-to-site rows. */
export const PROGRAM_SITES_SQL =
  'SELECT program_id AS programId, siteID AS siteId FROM synthetic.program_site ORDER BY program_id';

/** Every site with its stored pool columns, aliased because the migrations that added them differ in letter case. */
export const SITE_POOLS_SQL =
  `SELECT SiteID AS siteId, ${POOL_COLUMNS.map((c) => `${c} AS ${c}`).join(', ')} FROM tsettings ORDER BY SiteID`;

const infoSchema = z.object({
  ping: z.boolean(),
  sitemonitortask: z.string(),
  sitemonitortaskregistered: z.boolean(),
});

/** Inputs of {@link gatherLiveEvidence}; the caller owns and closes `db`. */
export interface LiveSources {
  db: ReadOnlyMssql;
  /** Legacy ColdFusion origin serving `harness/legacy-baseline/cfml/run.cfm`. */
  origin: string;
  env: EnvLike;
  fetch?: FetchLike;
  clock?: () => Date;
}

function isMissingFile(err: unknown): boolean {
  return (err as { cause?: { code?: unknown } } | null)?.cause?.code === 'ENOENT';
}

async function readNativeTasks(env: EnvLike): Promise<NativeTasksCapture | null> {
  try {
    return await readJson(path.join(pristineDir(env), NATIVE_TASKS_FILE), nativeTasksSchema);
  } catch (err) {
    if (isMissingFile(err)) return null;
    throw err;
  }
}

async function probeLegacy(sources: LiveSources): Promise<LegacyMonitorInfo> {
  const session = createHttpSession({ baseUrl: sources.origin, fetch: sources.fetch });
  const res = await session.get(INFO_PATH, { query: { info: '1' } });
  const url = `${sources.origin}${INFO_PATH}?info=1`;
  if (res.status !== 200) throw new Error(`${url} answered HTTP ${res.status}`);
  const body = res.json<unknown>();
  // ColdFusion may upper-case struct keys when it serializes them, so keys are matched case-insensitively.
  const keyed = body !== null && typeof body === 'object' ? Object.entries(body) : [];
  const parsed = infoSchema.safeParse(Object.fromEntries(keyed.map(([k, v]) => [k.toLowerCase(), v])));
  if (!parsed.success) {
    const detail = z.prettifyError(parsed.error);
    throw new Error(`${url} lacks ping, siteMonitorTask or siteMonitorTaskRegistered: ${detail}`);
  }
  return {
    ping: parsed.data.ping,
    siteMonitorTask: parsed.data.sitemonitortask,
    siteMonitorTaskRegistered: parsed.data.sitemonitortaskregistered,
  };
}

/** Reads the live catalog, `tsettings`, the stored-procedure catalog, the monitor probe and the native task capture. */
export async function gatherLiveEvidence(sources: LiveSources): Promise<LiveEvidence> {
  const clock = sources.clock ?? (() => new Date());
  const { db } = sources;
  const catalog = await db.readOnlyQuery<{ schemaName: string; tableName: string }>(CATALOG_TABLES_SQL);
  const tables = catalog.map((r) => ({ schema: r.schemaName, name: r.tableName }));
  const [siteIdRow] = await db.readOnlyQuery<{ tableCount: number }>(SITE_ID_TABLES_SQL);
  const hasProgramSite = tables.some((t) => sameText(t.schema, 'synthetic') && sameText(t.name, 'program_site'));
  const programSites = hasProgramSite ? await db.readOnlyQuery<ProgramSite>(PROGRAM_SITES_SQL) : null;
  const sites = await db.readOnlyQuery<SitePools>(SITE_POOLS_SQL);
  const storedProcedures = await liveCheck(db, { clock });
  const legacy = await probeLegacy(sources);
  const nativeTasks = await readNativeTasks(sources.env);
  return {
    checkedAt: clock().toISOString(),
    tables,
    siteIdTableCount: siteIdRow?.tableCount ?? 0,
    programSites,
    sites,
    storedProcedures,
    legacy,
    nativeTasks,
  };
}

