import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadBundleText, PropertiesSyntaxError } from './properties';
import type { BundleData, GeneratedBundles } from './rb';

type Layer = keyof GeneratedBundles;

export type BundleSource = { readonly dir: string; readonly bases: readonly string[] };

export type BundleSources = {
  readonly admin: BundleSource;
  readonly coreAssets: BundleSource | null;
  readonly global: BundleSource | null;
};

export type GenerateOptions = { readonly repoRoot: string; readonly outDir: string };

export type BundleFileError = { readonly dir: string; readonly file: string; readonly message: string };

/** Outcome of one run; file and entry counts are kept per layer so the CLI can report each directory. */
export type GenerateResult = {
  readonly outDir: string;
  readonly dirs: { readonly admin: string; readonly coreAssets: string | null; readonly global: string | null };
  readonly files: Readonly<Record<Layer, number>>;
  readonly entries: Readonly<Record<Layer, number>>;
  readonly errors: readonly BundleFileError[];
};

const HEADER = '// Generated by src/lib/resource-bundles/generate.ts. Do not edit.';
const EXTENSION = '.properties';
const PLAIN_MODULE_NAME = /^[A-Za-z0-9_-]+$/;
const ADMIN_DIR = 'core/mura/resourceBundle/resources';
const CORE_ASSETS_DIR = 'core/modules/v1/core_assets/resource_bundles';
const GLOBAL_DIRS = ['resourceBundles', 'resource_bundles'] as const;
const LAYERS: ReadonlyArray<readonly [Layer, string]> = [
  ['admin', 'admin'],
  ['coreAssets', 'core-assets'],
  ['global', 'global'],
];

/** Thrown when the admin bundle directory, which legacy always loads, is missing. */
export class MissingAdminBundlesError extends Error {
  constructor(path: string) {
    super(`Admin resource bundle directory not found: ${path}`);
    this.name = 'MissingAdminBundlesError';
  }
}

function compareCodeUnits(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function isAbsentError(error: unknown): boolean {
  const code = (error as NodeJS.ErrnoException | null)?.code;
  return code === 'ENOENT' || code === 'ENOTDIR';
}

async function statOrNull(path: string) {
  try {
    return await stat(path);
  } catch (error) {
    if (isAbsentError(error)) return null;
    throw error;
  }
}

function absolute(repoRoot: string, dir: string): string {
  return join(repoRoot, ...dir.split('/'));
}

function contains(parent: string, child: string): boolean {
  const rel = relative(parent, child);
  return rel === '' || (rel !== '..' && !rel.startsWith(`..${sep}`) && !isAbsolute(rel));
}

async function readSource(repoRoot: string, dir: string): Promise<BundleSource | null> {
  const path = absolute(repoRoot, dir);
  if (!(await statOrNull(path))?.isDirectory()) return null;
  const bases: string[] = [];
  for (const name of await readdir(path)) {
    if (!name.endsWith(EXTENSION) || !(await statOrNull(join(path, name)))?.isFile()) continue;
    bases.push(name.slice(0, -EXTENSION.length));
  }
  return { dir, bases: bases.sort(compareCodeUnits) };
}

/** Lists the `.properties` bases of the admin, core-assets and global bundle directories under `repoRoot`. */
export async function collectBundleSources(repoRoot: string): Promise<BundleSources> {
  const admin = await readSource(repoRoot, ADMIN_DIR);
  if (admin === null) throw new MissingAdminBundlesError(ADMIN_DIR);
  const coreAssets = await readSource(repoRoot, CORE_ASSETS_DIR);
  let global: BundleSource | null = null;
  for (const dir of GLOBAL_DIRS) {
    global = await readSource(repoRoot, dir);
    if (global !== null) break;
  }
  return { admin, coreAssets, global };
}

/** Module file name for a bundle base: the base itself when path-safe, else `x_` and 12 hex digits of its SHA-1. */
export function moduleFileName(base: string): string {
  if (PLAIN_MODULE_NAME.test(base)) return base;
  return `x_${createHash('sha1').update(base, 'utf8').digest('hex').slice(0, 12)}`;
}

/** Source text of the module holding one bundle file's entries or load error. */
export function renderBundleModule(data: BundleData): string {
  if ('error' in data) {
    return `${HEADER}\nconst bundle: { readonly error: string } = { error: ${JSON.stringify(data.error)} };\n\nexport default bundle;\n`;
  }
  const rows = data.entries.map(([key, value]) => `    [${JSON.stringify(key)}, ${JSON.stringify(value)}],\n`);
  return [
    `${HEADER}\n`,
    'const bundle: { readonly entries: ReadonlyArray<readonly [string, string]> } = {\n',
    rows.length === 0 ? '  entries: [],\n' : `  entries: [\n${rows.join('')}  ],\n`,
    '};\n\nexport default bundle;\n',
  ].join('');
}

/** Source text of the index module exporting `generatedBundles` over the per-file modules. */
export function renderIndexModule(sources: BundleSources): string {
  const imports: string[] = [];
  const layers: string[] = [];
  for (const [layer, subdir] of LAYERS) {
    const source = sources[layer];
    if (source === null) {
      layers.push(`  ${layer}: null,\n`);
      continue;
    }
    const files = source.bases.map((base) => {
      const id = `b${imports.length}`;
      imports.push(`import ${id} from ${JSON.stringify(`./${subdir}/${moduleFileName(base)}`)};\n`);
      // A literal "__proto__" key would set the prototype instead of an own property.
      const key = base === '__proto__' ? '["__proto__"]' : JSON.stringify(base);
      return `      ${key}: ${id},\n`;
    });
    const body = files.length === 0 ? '    files: {},\n' : `    files: {\n${files.join('')}    },\n`;
    layers.push(`  ${layer}: {\n    dir: ${JSON.stringify(source.dir)},\n${body}  },\n`);
  }
  return `${HEADER}\n${imports.join('')}\nexport const generatedBundles = {\n${layers.join('')}};\n`;
}

/** Regenerates `outDir` from the legacy bundle files under `repoRoot`; unparsable files become error modules. */
export async function generateResourceBundles(options: GenerateOptions): Promise<GenerateResult> {
  const repoRoot = resolve(options.repoRoot);
  const outDir = resolve(options.outDir);
  const sources = await collectBundleSources(repoRoot);
  const outputs: Array<readonly [string, string]> = [];
  const files: Record<Layer, number> = { admin: 0, coreAssets: 0, global: 0 };
  const entries: Record<Layer, number> = { admin: 0, coreAssets: 0, global: 0 };
  const errors: BundleFileError[] = [];

  for (const [layer, subdir] of LAYERS) {
    const source = sources[layer];
    if (source === null) continue;
    if (contains(outDir, absolute(repoRoot, source.dir)) || contains(absolute(repoRoot, source.dir), outDir)) {
      throw new Error(`Output directory ${outDir} overlaps bundle directory ${source.dir}`);
    }
    for (const base of source.bases) {
      const file = `${base}${EXTENSION}`;
      let data: BundleData;
      try {
        const bundle = loadBundleText(await readFile(join(absolute(repoRoot, source.dir), file)));
        data = { entries: [...bundle].sort(([a], [b]) => compareCodeUnits(a, b)) };
        entries[layer] += data.entries.length;
      } catch (error) {
        if (!(error instanceof PropertiesSyntaxError)) throw error;
        data = { error: error.message };
        errors.push({ dir: source.dir, file, message: error.message });
        console.warn(`warning: ${source.dir}/${file}: ${error.message}`);
      }
      files[layer] += 1;
      outputs.push([join(outDir, subdir, `${moduleFileName(base)}.ts`), renderBundleModule(data)]);
    }
  }
  outputs.push([join(outDir, 'index.ts'), renderIndexModule(sources)]);

  await rm(outDir, { recursive: true, force: true });
  for (const [path, text] of outputs) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, text, 'utf8');
  }

  const dirs = { admin: sources.admin.dir, coreAssets: sources.coreAssets?.dir ?? null, global: sources.global?.dir ?? null };
  return { outDir, dirs, files, entries, errors };
}

