import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { afterEach, describe, expect, it, vi } from 'vitest';
import {
  collectBundleSources,
  generateResourceBundles,
  MissingAdminBundlesError,
  moduleFileName,
  renderBundleModule,
  renderIndexModule,
  type BundleSources,
} from '@/lib/resource-bundles/generate';
import { createResourceBundles, type BundleData, type GeneratedBundles } from '@/lib/resource-bundles/rb';

const ADMIN = 'core/mura/resourceBundle/resources';
const CORE_ASSETS = 'core/modules/v1/core_assets/resource_bundles';
const HEADER = '// Generated by src/lib/resource-bundles/generate.ts. Do not edit.';
const MALFORMED = 'valid.key=Gr\\u00fc\\u00dfe\nbroken.key=bad \\u12 escape\n';

const roots: string[] = [];

afterEach(async () => {
  vi.restoreAllMocks();
  await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true })));
});

/** Creates a temporary repository root holding `files` (relative path → content) and empty `dirs`. */
async function makeRepo(files: Record<string, string>, dirs: readonly string[] = []): Promise<string> {
  const root = await mkdtemp(path.join(tmpdir(), 'rb-generate-'));
  roots.push(root);
  for (const dir of dirs) await mkdir(path.join(root, dir), { recursive: true });
  for (const [file, text] of Object.entries(files)) {
    await mkdir(path.dirname(path.join(root, file)), { recursive: true });
    await writeFile(path.join(root, file), text, 'utf8');
  }
  return root;
}

/** Every file under `dir` as relative path → content, sorted by path. */
async function readTree(dir: string): Promise<Record<string, string>> {
  const tree: Record<string, string> = {};
  for (const entry of (await readdir(dir, { recursive: true, withFileTypes: true })).filter((e) => e.isFile())) {
    const full = path.join(entry.parentPath, entry.name);
    tree[path.relative(dir, full).split(path.sep).join('/')] = await readFile(full, 'utf8');
  }
  return Object.fromEntries(Object.entries(tree).sort(([a], [b]) => (a < b ? -1 : 1)));
}

async function importGenerated(outDir: string): Promise<GeneratedBundles> {
  const url = pathToFileURL(path.join(outDir, 'index.ts')).href;
  const module = (await import(/* @vite-ignore */ url)) as { generatedBundles: GeneratedBundles };
  return module.generatedBundles;
}

const sha1Name = (base: string): string => `x_${createHash('sha1').update(base, 'utf8').digest('hex').slice(0, 12)}`;

describe('collectBundleSources', () => {
  it('throws MissingAdminBundlesError when the admin directory is absent', async () => {
    const root = await makeRepo({ 'resource_bundles/en.properties': 'a=b\n' });
    const error = await collectBundleSources(root).catch((caught: unknown) => caught);
    expect(error).toBeInstanceOf(MissingAdminBundlesError);
    expect(error).toMatchObject({ name: 'MissingAdminBundlesError', message: expect.stringContaining(ADMIN) });
  });

  it('throws MissingAdminBundlesError when the admin path is a file', async () => {
    const root = await makeRepo({ [ADMIN]: 'not a directory' });
    await expect(collectBundleSources(root)).rejects.toBeInstanceOf(MissingAdminBundlesError);
  });

  it('prefers resourceBundles/ over resource_bundles/ for the global layer', async () => {
    const root = await makeRepo({
      [`${ADMIN}/en.properties`]: 'a=b\n',
      'resourceBundles/de.properties': 'a=b\n',
      'resource_bundles/en.properties': 'a=b\n',
    });
    expect((await collectBundleSources(root)).global).toEqual({ dir: 'resourceBundles', bases: ['de'] });
  });

  it.each<[string, Record<string, string>, BundleSources['global']]>([
    ['only resource_bundles/', { 'resource_bundles/en.properties': 'a=b\n' }, { dir: 'resource_bundles', bases: ['en'] }],
    ['no global directory', {}, null],
  ])('global layer with %s', async (_label, files, expected) => {
    const root = await makeRepo({ [`${ADMIN}/en.properties`]: 'a=b\n', ...files });
    expect((await collectBundleSources(root)).global).toEqual(expected);
  });

  it('answers coreAssets null when the core-assets directory is absent, and lists it when present', async () => {
    const absent = await makeRepo({ [`${ADMIN}/en.properties`]: 'a=b\n' });
    expect((await collectBundleSources(absent)).coreAssets).toBeNull();
    const present = await makeRepo({ [`${ADMIN}/en.properties`]: 'a=b\n' }, [CORE_ASSETS]);
    expect((await collectBundleSources(present)).coreAssets).toEqual({ dir: CORE_ASSETS, bases: [] });
  });

  it('takes regular .properties files only, non-recursively, sorted by code unit with case kept', async () => {
    const root = await makeRepo(
      {
        [`${ADMIN}/zh_CN.properties`]: '',
        [`${ADMIN}/en.properties`]: '',
        [`${ADMIN}/EN_us.properties`]: '',
        [`${ADMIN}/de.properties`]: '',
        [`${ADMIN}/notes.txt`]: '',
        [`${ADMIN}/upper.PROPERTIES`]: '',
        [`${ADMIN}/en.properties.bak`]: '',
        [`${ADMIN}/nested/fr.properties`]: '',
      },
      [`${ADMIN}/dir.properties`],
    );
    expect((await collectBundleSources(root)).admin).toEqual({ dir: ADMIN, bases: ['EN_us', 'de', 'en', 'zh_CN'] });
  });
});

describe('moduleFileName', () => {
  it.each(['zh_CN', 'en', 'pt-BR', 'X_9'])('keeps the path-safe base %j', (base) => {
    expect(moduleFileName(base)).toBe(base);
  });

  it.each(['en US', 'zh.CN', 'ü', ''])('hashes the base %j', (base) => {
    expect(moduleFileName(base)).toBe(sha1Name(base));
    expect(moduleFileName(base)).toMatch(/^x_[0-9a-f]{12}$/);
  });
});

describe('renderBundleModule', () => {
  it('renders sorted entries as a typed default export, LF-terminated', () => {
    const text = renderBundleModule({ entries: [['a.key', 'Alpha'], ['b.key', 'Beta']] });
    expect(text).toBe(
      `${HEADER}\n` +
        'const bundle: { readonly entries: ReadonlyArray<readonly [string, string]> } = {\n' +
        '  entries: [\n' +
        '    ["a.key", "Alpha"],\n' +
        '    ["b.key", "Beta"],\n' +
        '  ],\n' +
        '};\n\nexport default bundle;\n',
    );
    expect(text).not.toContain('\r');
  });

  it.each<[string, BundleData]>([
    ['an empty bundle', { entries: [] }],
    ['a load error', { error: 'Malformed \\uxxxx encoding.' }],
  ])('renders %s', (_label, data) => {
    const text = renderBundleModule(data);
    expect(text.startsWith(`${HEADER}\n`)).toBe(true);
    expect(text.endsWith('export default bundle;\n')).toBe(true);
    expect(text).toContain('error' in data ? `{ readonly error: string } = { error: ${JSON.stringify(data.error)} }` : 'entries: [],');
  });

  it('encodes every string with JSON.stringify', () => {
    const value = 'quote " backslash \\ tab \t nl \n lone \uD800 literal \\u4f60 sep \u2028';
    const text = renderBundleModule({ entries: [['k"\\', value]] });
    expect(text).toContain(`[${JSON.stringify('k"\\')}, ${JSON.stringify(value)}]`);
    expect(text.split('\n')).toHaveLength(9);
  });

  it('is deterministic for the same input', () => {
    const data: BundleData = { entries: [['k', 'v']] };
    expect(renderBundleModule(data)).toBe(renderBundleModule({ entries: [['k', 'v']] }));
  });
});

describe('renderIndexModule', () => {
  const sources: BundleSources = {
    admin: { dir: ADMIN, bases: ['da', 'en US'] },
    coreAssets: null,
    global: { dir: 'resource_bundles', bases: ['__proto__', 'en'] },
  };

  it('imports every module in layer order and maps each real base to its import', () => {
    const text = renderIndexModule(sources);
    expect(text).toBe(
      `${HEADER}\n` +
        'import b0 from "./admin/da";\n' +
        `import b1 from "./admin/${sha1Name('en US')}";\n` +
        'import b2 from "./global/__proto__";\n' +
        'import b3 from "./global/en";\n' +
        '\nexport const generatedBundles = {\n' +
        '  admin: {\n' +
        `    dir: "${ADMIN}",\n` +
        '    files: {\n' +
        '      "da": b0,\n' +
        '      "en US": b1,\n' +
        '    },\n' +
        '  },\n' +
        '  coreAssets: null,\n' +
        '  global: {\n' +
        '    dir: "resource_bundles",\n' +
        '    files: {\n' +
        '      ["__proto__"]: b2,\n' +
        '      "en": b3,\n' +
        '    },\n' +
        '  },\n' +
        '};\n',
    );
    expect(renderIndexModule(sources)).toBe(text);
  });

  it('renders an empty layer with no imports', () => {
    const text = renderIndexModule({ admin: { dir: ADMIN, bases: [] }, coreAssets: { dir: CORE_ASSETS, bases: [] }, global: null });
    expect(text).not.toContain('import ');
    expect(text).toContain(`  coreAssets: {\n    dir: "${CORE_ASSETS}",\n    files: {},\n  },\n`);
    expect(text).toContain('  global: null,\n');
  });
});

describe('generateResourceBundles', () => {
  it('writes one module per bundle file plus an index rb.ts can serve', async () => {
    const root = await makeRepo({
      [`${ADMIN}/en.properties`]: '# comment\nLayout.Help=Help\nb.key=Bee\nno separator\n',
      [`${ADMIN}/de.properties`]: 'layout.help=Hilfe\n',
      [`${ADMIN}/en US.properties`]: 'k=spaced\n',
      [`${CORE_ASSETS}/en.properties`]: 'core.only=Core\n',
      'resource_bundles/en.properties': 'global.mycustomkey=success\n',
      'resource_bundles/__proto__.properties': 'proto.key=own\n',
    });
    const outDir = path.join(root, 'web/src/generated/resource-bundles');
    const result = await generateResourceBundles({ repoRoot: root, outDir });

    expect(result).toEqual({
      outDir,
      dirs: { admin: ADMIN, coreAssets: CORE_ASSETS, global: 'resource_bundles' },
      files: { admin: 3, coreAssets: 1, global: 2 },
      entries: { admin: 4, coreAssets: 1, global: 2 },
      errors: [],
    });
    expect(Object.keys(await readTree(outDir))).toEqual([
      'admin/de.ts',
      'admin/en.ts',
      `admin/${sha1Name('en US')}.ts`,
      'core-assets/en.ts',
      'global/__proto__.ts',
      'global/en.ts',
      'index.ts',
    ]);

    const generated = await importGenerated(outDir);
    expect(generated.admin.files['en']).toEqual({ entries: [['b.key', 'Bee'], ['layout.help', 'Help']] });
    expect(generated.admin.files['en US']).toEqual({ entries: [['k', 'spaced']] });
    expect(Object.hasOwn(generated.global?.files ?? {}, '__proto__')).toBe(true);
    const bundles = createResourceBundles(generated);
    expect(bundles.siteRbFor('en_US').rbKey('core.only')).toBe('Core');
    expect(bundles.siteRbFor('en_US').rbKey('global.mycustomkey')).toBe('success');
    expect(bundles.rbKey('de_DE', 'layout.help')).toBe('Hilfe');
  });

  it('records a malformed \\uXXXX file as an error module and warns without failing', async () => {
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => undefined);
    const root = await makeRepo({ [`${ADMIN}/en.properties`]: 'a=b\n', [`${ADMIN}/fr.properties`]: MALFORMED });
    const outDir = path.join(root, 'out');
    const result = await generateResourceBundles({ repoRoot: root, outDir });

    const message = 'Malformed \\uxxxx encoding.';
    expect(result.errors).toEqual([{ dir: ADMIN, file: 'fr.properties', message }]);
    expect(result.files.admin).toBe(2);
    expect(result.entries.admin).toBe(1);
    expect(warn).toHaveBeenCalledWith(`warning: ${ADMIN}/fr.properties: ${message}`);
    expect((await importGenerated(outDir)).admin.files['fr']).toEqual({ error: message });
  });

  it('produces byte-identical output across runs and replaces only the output directory', async () => {
    const root = await makeRepo({
      [`${ADMIN}/en.properties`]: 'z=last\na=first\r\nm=\\u00e9 middle\n',
      [`${ADMIN}/zh.properties`]: 'hello=\\u4f60\u597d\n',
      'resource_bundles/en.properties': 'g=global\n',
      'web/keep.txt': 'sibling',
      'web/out/stale.ts': 'stale',
    });
    const first = path.join(root, 'web/out');
    const second = path.join(root, 'web/out-2');
    await generateResourceBundles({ repoRoot: root, outDir: first });
    await generateResourceBundles({ repoRoot: root, outDir: second });

    const tree = await readTree(first);
    expect(tree).toEqual(await readTree(second));
    expect(tree).not.toHaveProperty('stale.ts');
    expect(Object.values(tree).every((text) => text.endsWith('\n') && !text.includes('\r'))).toBe(true);
    expect(JSON.stringify(tree)).not.toContain(root);
    expect(await readFile(path.join(root, 'web/keep.txt'), 'utf8')).toBe('sibling');
    expect(await readFile(path.join(root, ADMIN, 'en.properties'), 'utf8')).toBe('z=last\na=first\r\nm=\\u00e9 middle\n');
  });

  it.each([ADMIN, `${ADMIN}/generated`, 'core'])('refuses an output directory overlapping a bundle directory (%s)', async (out) => {
    const root = await makeRepo({ [`${ADMIN}/en.properties`]: 'a=b\n' });
    await expect(generateResourceBundles({ repoRoot: root, outDir: path.join(root, out) })).rejects.toThrow(/overlaps bundle directory/);
    expect(await readFile(path.join(root, ADMIN, 'en.properties'), 'utf8')).toBe('a=b\n');
  });

  it('propagates MissingAdminBundlesError without touching the output directory', async () => {
    const root = await makeRepo({ 'out/keep.ts': 'kept' });
    await expect(generateResourceBundles({ repoRoot: root, outDir: path.join(root, 'out') })).rejects.toBeInstanceOf(
      MissingAdminBundlesError,
    );
    expect(await readFile(path.join(root, 'out/keep.ts'), 'utf8')).toBe('kept');
  });
});
