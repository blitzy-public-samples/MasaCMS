/** A global pattern matching each code point of `ranges`. */
function codePointClass(ranges: readonly (readonly [number, number])[]): RegExp {
  return new RegExp(`[${ranges.map(([first, last]) => `\\u{${first.toString(16)}}-\\u{${last.toString(16)}}`).join('')}]`, 'gu');
}

const IGNORABLE = codePointClass(LEGACY_IGNORABLE_RANGES);
const SPECIAL_OR_IGNORABLE = codePointClass([...LEGACY_SPECIAL_RANKS.map(([codePoint]) => [codePoint, codePoint] as const), ...LEGACY_IGNORABLE_RANGES]);

/** Tie-break key character of each special: U+0020 + its rank, all below `OTHER`. */
const SPECIAL_KEY: ReadonlyMap<string, string> = new Map(
  LEGACY_SPECIAL_RANKS.map(([codePoint, rank]) => [String.fromCodePoint(codePoint), String.fromCharCode(0x20 + rank)]),
);

/** Tie-break key character of every other code point. */
const OTHER = '~';

const COLLATOR = new Intl.Collator('en-US', { sensitivity: 'accent' });

/** `value` without its specials and ignorables, in NFD, without trailing spaces: the text SQL Server compares case-insensitively and accent-sensitively first. */
export function legacyWordText(value: string): string {
  return value.replace(SPECIAL_OR_IGNORABLE, '').normalize('NFD').replace(/ +$/, '');
}

/** The tie-break key of `value`: a special's rank, or `OTHER` per non-ignorable NFKD code point of any other character, trailing `OTHER`s dropped; ordered by code unit. */
export function legacyWordSpecial(value: string): string {
  let key = '';
  for (const char of value.replace(IGNORABLE, '')) {
    key += SPECIAL_KEY.get(char) ?? OTHER.repeat([...char.normalize('NFKD').replace(IGNORABLE, '')].length);
  }
  return key.replace(/~+$/, '');
}

/** SQL Server's order of two nvarchar values: `legacyWordText` under ICU, then `legacyWordSpecial`; 0 exactly when SQL Server's `=` holds. */
export function compareLegacyText(a: string, b: string): number {
  const byText = COLLATOR.compare(legacyWordText(a), legacyWordText(b));
  if (byText !== 0) return byText;
  const [x, y] = [legacyWordSpecial(a), legacyWordSpecial(b)];
  if (x === y) return 0;
  return x < y ? -1 : 1;
}
