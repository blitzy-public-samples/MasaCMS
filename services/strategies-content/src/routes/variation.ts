/** `/_api/resource/variation`: handleAPIRequest's variation branch (contentServer.cfc:649-650), which runs variation.js.cfm. */
import { AuthDenial, assertSiteMatches, type Opt2RouteConfig } from '@opt2/platform/auth';
import { LEGACY_HTML_CONTENT_TYPE, LegacyServiceUnavailableError } from '@opt2/platform/legacy-compat';
import { sendLegacyResponse, type FastifyInstance, type FastifyReply, type FastifyRequest } from '@opt2/platform/service-kit';
import type { DomainDeps } from '../domain/context.js';
import { variationsEnabled } from '../domain/variations.js';

/** The route context these routes read: a structural subset of `ContentRouteContext`. */
export interface VariationRouteContext {
  domain: Pick<DomainDeps, 'config'>;
}

/** handleAPIRequest's variation endpoint; legacy matches it as a path prefix. */
export const VARIATION_PATH = '/_api/resource/variation';

/** A request's query as Fastify parses it: a repeated key holds an array. */
export type VariationQuery = Readonly<Record<string, string | readonly string[] | undefined>>;

type VariationRoute = { Querystring: VariationQuery };

// Public, as legacy serves the script to any visitor. The handler checks `siteid` only once the branch is taken: legacy
// answers an unmatched request whatever site it names, which the platform's check of every supplied `siteid` would not.
const ROUTE: { opt2: Opt2RouteConfig } = Object.freeze({ opt2: Object.freeze({ public: true, transport: 'service', siteCheck: false }) });

/** handleAPIRequest falling through every endpoint: an empty page. */
const UNMATCHED = Object.freeze({ status: 200, headers: { 'Content-Type': LEGACY_HTML_CONTENT_TYPE }, body: '' });

/** `url.siteid` as the CFML url scope holds it: the key matched without case, a repeated key's values joined with `,`. */
export function urlSiteId(query: VariationQuery): string | undefined {
  let siteId: string | undefined;
  for (const [key, value] of Object.entries(query)) {
    if (value !== undefined && key.toLowerCase() === 'siteid') siteId = typeof value === 'string' ? value : value.join(',');
  }
  return siteId;
}

/** Answers one variation request: the unmatched page while the branch is not taken, otherwise the fail-closed 503. */
async function serveVariation(ctx: VariationRouteContext, request: FastifyRequest<VariationRoute>, reply: FastifyReply): Promise<FastifyReply> {
  const siteId = urlSiteId(request.query);
  if (siteId === undefined || !variationsEnabled(ctx.domain.config)) return sendLegacyResponse(reply, UNMATCHED);
  const claims = request.opt2Auth.user;
  if (claims === undefined) throw AuthDenial.unauthenticated('missing-credential');
  assertSiteMatches(siteId, claims);
  // The script is mura.min.js plus site paths, theme, content-renderer, resource-bundle and tracking values only the CFML
  // runtime holds; it embeds no variation data (the browser fetches targeting through the JSON API), so the route fails
  // closed rather than approximate it.
  throw new LegacyServiceUnavailableError('The variation script is generated by the CFML runtime', 'auto', 'variation-script-runtime');
}

/** Registers `resourceVariationGet` and `resourceVariationPathGet`; legacy authenticates neither. */
export function registerVariationRoutes(app: FastifyInstance, ctx: VariationRouteContext): void {
  for (const url of [VARIATION_PATH, `${VARIATION_PATH}/*`]) {
    app.get<VariationRoute>(url, { config: ROUTE }, (request, reply) => serveVariation(ctx, request, reply));
  }
}
