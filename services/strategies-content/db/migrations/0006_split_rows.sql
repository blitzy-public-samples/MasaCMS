-- strategies-content shares of the split tables tclassextend* (baseTable tcontent) and ttrash (content object classes); varchar and nvarchar map to text by the canonical type map.
CREATE TABLE content.extend_subtype (
  tenant_id uuid NOT NULL,
  subtypeid char(35) NOT NULL,
  siteid text,
  basetable text,
  basekeyfield text,
  datatable text,
  type text,
  subtype text,
  isactive smallint,
  notes text,
  lastupdate timestamp(3) without time zone,
  datecreated timestamp(3) without time zone,
  lastupdateby text,
  hassummary smallint DEFAULT 1,
  hasbody smallint DEFAULT 1,
  description text,
  availablesubtypes text,
  iconclass text,
  hasassocfile smallint DEFAULT 1,
  hasconfigurator integer DEFAULT 1,
  adminonly integer,
  PRIMARY KEY (tenant_id, subtypeid)
);
ALTER TABLE content.extend_subtype ENABLE ROW LEVEL SECURITY; ALTER TABLE content.extend_subtype FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON content.extend_subtype
  USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
  WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);

